import fs from "node:fs";
import path from "node:path";
import { config } from "../core/config";
import { sentryToolNames } from "../sentry/mcp-config";

/**
 * Tool policies for the two agent jobs (PLAN §6.2, §6.5). Sessions run in
 * permission mode `dontAsk`: anything not allowed here is denied.
 */
const READ_ONLY_GIT = [
  "Bash(git log)",
  "Bash(git log *)",
  "Bash(git show *)",
  "Bash(git blame *)",
  "Bash(git diff)",
  "Bash(git diff *)",
  "Bash(git status)",
];

export const ALWAYS_DENIED = [
  "Bash(git commit *)",
  "Bash(git push *)",
  "Bash(git push)",
  "Bash(git remote *)",
  "Bash(git config *)",
  "Bash(git reset *)",
  "Bash(git checkout *)",
  "Bash(gh *)",
  "Bash(curl *)",
  "Bash(wget *)",
  "Bash(ssh *)",
  "Bash(scp *)",
  "Bash(nc *)",
  "WebFetch",
  "WebSearch",
];

export type ToolPolicy = { tools: string[]; allowedTools: string[]; disallowedTools: string[] };

export function triagePolicy(): ToolPolicy {
  return {
    tools: ["Read", "Grep", "Glob", "Bash"],
    allowedTools: ["Read(./**)", "Grep", "Glob", ...READ_ONLY_GIT, ...sentryToolNames()],
    disallowedTools: ["Edit", "Write", "NotebookEdit", ...ALWAYS_DENIED],
  };
}

/**
 * Wrapper scripts for the project's build and test commands, written outside
 * the worktree (so the agent cannot edit them and they are never committed).
 * The agent may run exactly these two paths; quoting inside the owner's
 * commands never has to survive a permission-rule parser.
 */
export function writeCommandScripts(projectId: number, cmds: { build: string | null; test: string | null }) {
  const dir = path.join(config().dataDir, "bin", String(projectId));
  fs.mkdirSync(dir, { recursive: true });
  const out: { build?: string; test?: string } = {};
  for (const [name, cmd] of Object.entries(cmds) as Array<["build" | "test", string | null]>) {
    const file = path.join(dir, `${name}.sh`);
    if (!cmd) {
      fs.rmSync(file, { force: true });
      continue;
    }
    fs.writeFileSync(file, `#!/bin/sh\n# Generated by sentry-harness from the project's ${name}_cmd. Runs in the current directory.\n${cmd}\n`, { mode: 0o755 });
    out[name] = file;
  }
  return out;
}

export function fixPolicy(scripts: { build?: string; test?: string }): ToolPolicy {
  const run = [scripts.build, scripts.test].filter(Boolean).flatMap((p) => [`Bash(${p})`, `Bash(${p} *)`]);
  return {
    tools: ["Read", "Edit", "Write", "Grep", "Glob", "Bash"],
    allowedTools: ["Read(./**)", "Edit(./**)", "Write(./**)", "Grep", "Glob", ...READ_ONLY_GIT, ...run, ...sentryToolNames()],
    disallowedTools: ["NotebookEdit", ...ALWAYS_DENIED],
  };
}
